"""Batch publication of Actor Factory presets to the Apify platform.

Stages each preset as a self-contained actor package (generated ``.actor/`` +
``src/main.py`` plus the engine files the generated Dockerfile COPYs),
validates the package, then delegates the upload to the apify-cli.

The staging layout mirrors what ``apify push`` expects: a directory containing
``.actor/actor.json``; every path the Dockerfile references must exist inside
the staged directory or the platform build fails after upload.

Results are recorded incrementally to ``results.json`` in the staging root so
an interrupted batch can be resumed with ``--resume`` without re-pushing
actors that already landed.
"""

from __future__ import annotations

import json
import logging
import shutil
import subprocess
import time
from dataclasses import dataclass
from typing import TYPE_CHECKING

from actor_factory.generator import generate_actor, validate_generated
from actor_factory.presets import ALL_PRESETS

if TYPE_CHECKING:
    from collections.abc import Callable, Iterator
    from pathlib import Path

    from actor_factory.spec import ActorSpec

logger = logging.getLogger(__name__)

# Paths (relative to repo root) that the generated Dockerfile COPYs.
# The engine lives in src/pry/engine since the src-layout restructure.
# Keep in sync with generator._DOCKERFILE_TEMPLATE.
ENGINE_FILES: tuple[str, ...] = ("requirements.lock",)
ENGINE_DIRS: tuple[str, ...] = (
    "actor_factory",
    "src/pry",
)

PUSH_TIMEOUT_SECONDS = 300
PUSH_RETRIES = 3
INTER_PUSH_DELAY_SECONDS = 2.0
RESULTS_FILENAME = "results.json"


@dataclass(frozen=True)
class PushResult:
    """Outcome of one actor's stage+push cycle."""

    name: str
    ok: bool
    detail: str = ""


def sorted_specs(only: list[str] | None = None) -> list[ActorSpec]:
    """All presets (or a filtered subset), ordered by name for determinism."""
    if only:
        missing = [name for name in only if name not in ALL_PRESETS]
        if missing:
            msg = f"unknown preset(s): {', '.join(missing)}"
            raise KeyError(msg)
        names = only
    else:
        names = sorted(ALL_PRESETS)
    return [ALL_PRESETS[name] for name in names]


# Third-party packages the actor runtime actually imports (engine modules +
# actor_factory), pinned by extracting exact versions from the repo lock.
# The full repo lock is NOT shipped: it contains dev/test deps (pact, pandas,
# pytest...) that conflict on the platform builder and bloat actor images.
ACTOR_RUNTIME_PACKAGES: tuple[str, ...] = (
    "httpx",
    "pydantic",
    "pydantic-settings",
    "trafilatura",
    "structlog",
    "markdownify",
    "readability-lxml",
    "cloudscraper",
    "aiohttp",
    "aiohttp_socks",
    "prometheus_client",
    "opentelemetry-api",
    "opentelemetry-sdk",
)


# requirements.lock normalizes - vs _ in dist names; match either.
def _lock_name(package: str) -> str:
    return package.replace("-", "_").lower()


def _actor_lock_contents(repo_lock: Path) -> str:
    """Curated actor lock: pins for ACTOR_RUNTIME_PACKAGES extracted from
    the repo lock (single source of truth for versions).

    The ``-e git+ssh://...#egg=pry`` lines are developer checkout
    conveniences and cannot resolve on Apify's builder (no SSH keys); every
    module the runtime needs is COPYed into the image by the generated
    Dockerfile instead.
    """
    wanted = {_lock_name(p): p for p in ACTOR_RUNTIME_PACKAGES}
    found: dict[str, str] = {}
    for line in repo_lock.read_text().splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith(("#", "-")):
            continue
        name = _lock_name(stripped.split("==")[0].split("[")[0])
        if name in wanted and name not in found:
            found[name] = stripped
    missing = sorted(wanted[n] for n in wanted if n not in found)
    if missing:
        msg = f"actor runtime packages missing from repo requirements.lock: {', '.join(missing)}"
        raise ValueError(msg)
    header = (
        "# Generated by actor_factory.publish._actor_lock_contents - DO NOT EDIT.\n"
        "# Runtime pins for Pry Actor images, extracted from the repo lock.\n"
        "# apify-sdk + playwright are installed separately by the Dockerfile.\n"
    )
    return header + "\n".join(found[p] for p in sorted(found)) + "\n"


def scan_staged_for_secrets(stage: Path, repo_root: Path) -> tuple[bool, str]:
    """F44 defense-in-depth: gitleaks scan of a staged actor package.

    Runs before upload so a leaked credential can never reach the Apify
    registry even if upstream scans missed it. A missing gitleaks binary
    fails OPEN with a note (the repo CI runs the canonical scan); any
    finding fails CLOSED.

    Returns ``(clean, report)``.
    """
    gitleaks = shutil.which("gitleaks")
    if gitleaks is None:
        return True, "gitleaks not installed — staged scan skipped (CI enforces)"
    # Deliberately NO --config: the repo .gitleaks.toml carries a broad
    # stopword allowlist tuned for OUR source tree. Staged packages are
    # shipped artifacts — scan them under gitleaks' strict DEFAULT rules.
    cmd = [gitleaks, "detect", "--source", str(stage), "--no-git", "--report-format", "text"]
    try:
        proc = subprocess.run(  # noqa: S603 - fixed argv, paths from staging
            cmd,
            capture_output=True,
            text=True,
            timeout=120,
        )
    except subprocess.TimeoutExpired:
        return False, "gitleaks scan timed out after 120s — refusing upload"
    if proc.returncode == 0:
        return True, "clean"
    report = (proc.stdout or proc.stderr or "").strip()
    return False, f"secret scan findings:\n{report[-2000:]}"


def stage_actor(spec: ActorSpec, repo_root: Path, staging_root: Path) -> Path:
    """Render one preset into ``staging_root/<name>/`` with engine files.

    Raises ValueError on invalid generated packages and FileNotFoundError
    when an engine file referenced by the Dockerfile is absent.
    """
    stage = staging_root / spec.name
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)

    generated = generate_actor(spec, stage)
    problems = validate_generated(generated.files)
    if problems:
        msg = f"{spec.name}: invalid generated package: {problems}"
        raise ValueError(msg)

    for name in ENGINE_FILES:
        src = repo_root / name
        if not src.is_file():
            msg = f"engine file missing at repo root: {name}"
            raise FileNotFoundError(msg)
        if name == "requirements.lock":
            (stage / name).write_text(_actor_lock_contents(src))
        else:
            shutil.copy2(src, stage / name)
    for dirname in ENGINE_DIRS:
        src = repo_root / dirname
        if not src.is_dir():
            msg = f"engine directory missing at repo root: {dirname}"
            raise FileNotFoundError(msg)
        shutil.copytree(
            src,
            stage / dirname,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
        )
    # F44 defense-in-depth: no staged package ships without a secret scan.
    clean, report = scan_staged_for_secrets(stage, repo_root)
    if not clean:
        msg = f"{spec.name}: refusing to stage — {report}"
        raise ValueError(msg)
    return stage


def _cli_path() -> str | None:
    return shutil.which("npx")


def check_auth() -> tuple[bool, str]:
    """Fail-fast auth probe: apify-cli must be logged in before a batch."""
    npx = _cli_path()
    if not npx:
        return False, "apify-cli prerequisite missing: npx not found on PATH"
    proc = subprocess.run(  # noqa: S603 - fixed argv, no shell
        [npx, "--yes", "apify-cli", "info"],
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    if proc.returncode == 0:
        return True, (proc.stdout or "").strip()[:200]
    detail = ((proc.stderr or "") + (proc.stdout or "")).strip()[:200]
    return False, f"not logged in to apify-cli (run: apify login): {detail}"


def push_actor(stage: Path, actor_id: str | None = None) -> tuple[bool, str]:
    """Upload one staged package via apify-cli (uses stored login state).

    ``actor_id`` targets an org-owned actor (``orgname~actor-name``) -
    required once presets live under an Apify organization instead of a
    personal account.
    """
    npx = _cli_path()
    if not npx:
        return False, "apify-cli prerequisite missing: npx not found on PATH"
    argv = [npx, "--yes", "apify-cli", "push", "--force"]
    if actor_id:
        argv.append(actor_id)
    argv += ["--dir", str(stage)]
    detail = ""
    for attempt in range(1, PUSH_RETRIES + 1):
        try:
            proc = subprocess.run(  # noqa: S603 - fixed argv, no shell
                argv,
                capture_output=True,
                text=True,
                timeout=PUSH_TIMEOUT_SECONDS,
                check=False,
            )
        except subprocess.TimeoutExpired:
            detail = f"timed out after {PUSH_TIMEOUT_SECONDS}s"
            logger.warning("push timed out (attempt %d/%d)", attempt, PUSH_RETRIES)
            time.sleep(3 * attempt)
            continue
        if proc.returncode == 0:
            tail = (proc.stdout or "").strip()
            return True, tail[-400:] if tail else "pushed"
        detail = ((proc.stderr or "") + (proc.stdout or "")).strip()[-400:]
        logger.warning("push failed (attempt %d/%d): %s", attempt, PUSH_RETRIES, detail)
        time.sleep(3 * attempt)
    return False, detail


def _results_path(staging_root: Path) -> Path:
    return staging_root / RESULTS_FILENAME


def load_results(staging_root: Path) -> dict[str, PushResult]:
    path = _results_path(staging_root)
    if not path.is_file():
        return {}
    raw = json.loads(path.read_text())
    return {name: PushResult(name=name, **entry) for name, entry in raw.items()}


def _save_result(staging_root: Path, results: dict[str, PushResult], result: PushResult) -> None:
    results[result.name] = result
    payload = {r.name: {"ok": r.ok, "detail": r.detail} for r in results.values()}
    _results_path(staging_root).write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")


def run_batch(
    repo_root: Path,
    staging_root: Path,
    *,
    only: list[str] | None = None,
    dry_run: bool = False,
    resume: bool = False,
    push_fn: Callable[[Path, str | None], tuple[bool, str]] | None = None,
    actor_id_prefix: str | None = None,
    delay_seconds: float = INTER_PUSH_DELAY_SECONDS,
) -> Iterator[PushResult]:
    """Stage (and unless dry-run, push) each preset, yielding results.

    With ``resume``, presets already recorded ok in results.json are skipped.
    Results are persisted incrementally so an interrupted batch resumes clean.
    """
    push = push_fn or push_actor
    if push_fn is None and not dry_run:
        # Real transport only: fail fast on missing login before any staging.
        auth_ok, auth_detail = check_auth()
        if not auth_ok:
            raise RuntimeError(auth_detail)
    staging_root.mkdir(parents=True, exist_ok=True)
    done = load_results(staging_root) if resume else {}

    for spec in sorted_specs(only):
        if resume and done.get(spec.name) is not None and done[spec.name].ok:
            logger.info("skip %s (already pushed)", spec.name)
            continue
        try:
            stage = stage_actor(spec, repo_root, staging_root)
        except Exception as exc:  # noqa: BLE001 - per-actor isolation, recorded not raised
            result = PushResult(name=spec.name, ok=False, detail=str(exc)[:400])
            logger.error("stage failed for %s: %s", spec.name, result.detail)
            if not dry_run:
                _save_result(staging_root, done, result)
            yield result
            continue

        if dry_run:
            logger.info("dry-run OK: %s staged at %s", spec.name, stage)
            yield PushResult(name=spec.name, ok=True, detail="dry-run")
            continue

        target_id = f"{actor_id_prefix}~{spec.name}" if actor_id_prefix else None
        ok, detail = push(stage, target_id)
        result = PushResult(name=spec.name, ok=ok, detail=detail)
        _save_result(staging_root, done, result)
        level = logging.INFO if ok else logging.ERROR
        logger.log(level, "%s: %s", spec.name, "pushed" if ok else f"FAILED: {detail}")
        yield result
        time.sleep(delay_seconds)
